#!/usr/bin/env node
// Builds release/Castle-Kitchen.ppf (PPF3, forward, block check, no undo) from the vanilla US ROM
// to the main ROM, verifies it byte for byte, and writes release/release.js for the page.
// Usage: node tools/build-release.js --vanilla PATH [--rom PATH] [--build N]
'use strict';
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const kitchen = require('../release-core.js');

const root = path.resolve(__dirname, '..');
const args = process.argv.slice(2);
const option = name => { const i = args.indexOf(name); return i >= 0 ? args[i + 1] : null; };
const vanillaPath = option('--vanilla');
const romPath = option('--rom') || path.join(root, 'mainBIN', "Castlevania Dissonance in Castle's Kitchen.gba");
if (!vanillaPath) throw new Error('Pass --vanilla with the path to the clean US ROM.');

const VANILLA = {size: 0x800000, sha256: '85E0A40DE22783BADBBC95D6BCAD68A3A25D0916C4111956213F8281358A61DB'};
const sha = bytes => crypto.createHash('sha256').update(bytes).digest('hex').toUpperCase();
const vanilla = new Uint8Array(fs.readFileSync(vanillaPath));
const rom = new Uint8Array(fs.readFileSync(romPath));
if (vanilla.length !== VANILLA.size || sha(vanilla) !== VANILLA.sha256) throw new Error('That is not the clean US ROM.');
if (rom.length < vanilla.length || rom.length > 0x2000000) throw new Error('Unexpected main ROM size.');

// Build number: keep the previous one if the main ROM is unchanged, otherwise raise it.
const dataPath = path.join(root, 'release', 'release.js');
let previous = null;
if (fs.existsSync(dataPath)) {
  const text = fs.readFileSync(dataPath, 'utf8');
  previous = JSON.parse(text.slice(text.indexOf('{'), text.lastIndexOf('}') + 1));
}
const romSha = sha(rom);
const build = option('--build') ? Number(option('--build')) :
  !previous ? 1 : previous.result.sha256 === romSha ? previous.build : previous.build + 1;
if (!Number.isInteger(build) || build < 1 || build > 99) throw new Error('Invalid build number.');
const version = 'K.' + String(build).padStart(2, '0');

// Records: merge changed runs separated by fewer than 9 equal bytes (the record header size).
const records = [];
const differs = i => i >= vanilla.length || vanilla[i] !== rom[i];
for (let i = 0; i < rom.length;) {
  if (!differs(i)) { i++; continue; }
  let end = i + 1, last = i + 1;
  while (end < rom.length && end - i < 255) {
    if (differs(end)) last = end + 1;
    else if (end - last >= 8) break;
    end++;
  }
  records.push([i, last - i]);
  i = last;
}

const description = `Castlevania Dissonance in Castle's Kitchen ${version}`.padEnd(50, ' ').slice(0, 50);
const size = 60 + 1024 + records.reduce((n, [, len]) => n + 9 + len, 0);
const ppf = new Uint8Array(size);
const view = new DataView(ppf.buffer);
ppf.set(Buffer.from('PPF30', 'ascii'), 0);
ppf[5] = 2;
ppf.set(Buffer.from(description, 'ascii'), 6);
ppf[56] = 0; ppf[57] = 1; ppf[58] = 0; ppf[59] = 0; // image BIN, block check on, no undo
ppf.set(vanilla.subarray(0x9320, 0x9320 + 1024), 60);
let at = 1084;
for (const [offset, len] of records) {
  view.setBigUint64(at, BigInt(offset), true);
  ppf[at + 8] = len;
  ppf.set(rom.subarray(offset, offset + len), at + 9);
  at += 9 + len;
}
if (at !== size) throw new Error('PPF size mismatch.');

// Verify with the same code the page uses.
const parsed = kitchen.parsePpf(ppf);
const result = kitchen.apply(vanilla, parsed);
if (result.length !== rom.length || sha(result) !== romSha) throw new Error('The PPF does not rebuild the main ROM.');

fs.mkdirSync(path.join(root, 'release'), {recursive: true});
fs.writeFileSync(path.join(root, 'release', 'Castle-Kitchen.ppf'), ppf);
const data = {
  title: "Castlevania Dissonance in Castle's Kitchen",
  build, version,
  built: new Date().toISOString().slice(0, 10),
  ppf: {file: 'release/Castle-Kitchen.ppf', name: `Castle-Kitchen-${version}.ppf`, size: ppf.length, sha256: sha(ppf), records: records.length},
  vanilla: {name: 'Castlevania - Harmony of Dissonance (USA).gba', size: vanilla.length, sha256: VANILLA.sha256,
    crc32: kitchen.hex(kitchen.crc32(vanilla))},
  result: {name: "Castlevania Dissonance in Castle's Kitchen.gba", size: rom.length, sha256: romSha,
    crc32: kitchen.hex(kitchen.crc32(rom))},
};
fs.writeFileSync(dataPath, '// Generated by tools/build-release.js from the vanilla US ROM and the main ROM. Do not edit by hand.\n' +
  'globalThis.HodKitchenRelease = ' + JSON.stringify(data, null, 1) + ';\n');
console.log(`${version}: ${records.length} records, PPF ${ppf.length} bytes, SHA-256 ${data.ppf.sha256}`);
console.log(`vanilla -> ${romSha} (${rom.length} bytes) verified`);
